export function buildInfluencerScript({
  influencer,
  promoType,
  name = "",
  benefit = "",
  cta = "",
  style,
  language = "es-latam",
  facePresetId = "preset",
  customFaceTrait = "",
  personaStyleId = "preset",
  wardrobeId = "preset",
  customWardrobeText = "",
  virtualEnvironmentId = "preset",
  compositingModeId = "realistic-relight",
  customEnvironmentText = "",
  customEnvironmentImageTag = "",
  voiceDirective = "",
  extraNotes = "",
  useInfluencerAvatar = true,
  hasUploadedAsset = false,
}) {
  const effectivePromoType =
    promoType || influencer?.defaultPromoType || "product";
  const effectiveStyle = style || influencer?.defaultStyle || "showcase";

  const langObj =
    INFLUENCER_LANGUAGES.find((l) => l.id === language) ||
    INFLUENCER_LANGUAGES[0];
  const tpl = LANGUAGE_TEMPLATES[langObj.id] || LANGUAGE_TEMPLATES["es-latam"];
  const isSpanish = langObj.id.startsWith("es");

  const cleanName =
    name.trim() ||
    (isSpanish ? influencer?.defaultName : "") ||
    (effectivePromoType === "product"
      ? tpl.defaults.productName
      : effectivePromoType === "service"
      ? tpl.defaults.serviceName
      : tpl.defaults.videoName);

  const cleanBenefit =
    benefit.trim() ||
    (isSpanish ? influencer?.defaultBenefit : "") ||
    tpl.defaults.benefit;

  const cleanCta =
    cta.trim() ||
    (isSpanish ? influencer?.defaultCta : "") ||
    tpl.defaults.cta;

  const facePresetObj = INFLUENCER_FACE_PRESETS.find(
    (f) => f.id === facePresetId
  );
  const personaStyleObj = INFLUENCER_PERSONA_STYLES.find(
    (ps) => ps.id === personaStyleId
  );
  const wardrobeObj = INFLUENCER_WARDROBE_OPTIONS.find(
    (w) => w.id === wardrobeId
  );
  const virtualEnvObj = INFLUENCER_VIRTUAL_ENVIRONMENTS.find(
    (env) => env.id === virtualEnvironmentId
  );
  const compositingObj =
    INFLUENCER_COMPOSITING_MODES.find((cm) => cm.id === compositingModeId) ||
    INFLUENCER_COMPOSITING_MODES[0];

  const customTraitFragments = [];
  if (customFaceTrait.trim()) {
    customTraitFragments.push(
      `Custom facial traits: ${customFaceTrait.trim()}`
    );
  } else if (facePresetObj?.traitPrompt) {
    customTraitFragments.push(`Facial appearance: ${facePresetObj.traitPrompt}`);
  }
  if (personaStyleObj?.directive) {
    customTraitFragments.push(
      `Environment & visual style: ${personaStyleObj.directive}`
    );
  }
  if (wardrobeId === "custom" && customWardrobeText.trim()) {
    customTraitFragments.push(
      `Wardrobe/Clothing: wearing ${customWardrobeText.trim()}`
    );
  } else if (wardrobeObj?.directive) {
    customTraitFragments.push(`Wardrobe/Clothing: ${wardrobeObj.directive}`);
  }

  // HeyGen Virtual Studio & Chroma / Realistic Compositing Directives
  if (compositingModeId === "pure-chroma-green") {
    customTraitFragments.push(
      `Virtual Studio & Compositing: ${compositingObj.directive}`
    );
  } else if (virtualEnvironmentId === "custom-environment") {
    const customEnvDesc =
      customEnvironmentText.trim() ||
      "modern custom virtual studio background with clean architectural lighting";
    customTraitFragments.push(
      `Virtual Studio Environment: ${customEnvDesc}${
        customEnvironmentImageTag
          ? ` (matching background reference ${customEnvironmentImageTag})`
          : ""
      }. Lighting & Compositing: ${compositingObj.directive}`
    );
  } else if (virtualEnvObj && virtualEnvObj.id !== "preset") {
    customTraitFragments.push(
      `Virtual Studio Environment (${virtualEnvObj.name}): ${virtualEnvObj.environmentPrompt}. Lighting Integration: ${virtualEnvObj.lightingMatch}. Compositing Engine: ${compositingObj.directive}`
    );
  }

  if (voiceDirective.trim()) {
    customTraitFragments.push(`Voice & tone: ${voiceDirective.trim()}`);
  }

  const baseActorPrompt = influencer
    ? influencer.visualPrompt
    : "Realistic charismatic UGC creator speaking directly to the camera in a vertical 9:16 social media video";

  const actorDescription =
    customTraitFragments.length > 0
      ? `${baseActorPrompt}. ${customTraitFragments.join(". ")}.`
      : `${baseActorPrompt}.`;

  const imageRefs = [];
  if (useInfluencerAvatar) {
    imageRefs.push("@image1 as the AI influencer face and character speaking to camera");
  }
  if (hasUploadedAsset) {
    const assetIdx = useInfluencerAvatar ? "@image2" : "@image1";
    imageRefs.push(
      effectivePromoType === "product"
        ? `featuring and holding the product from ${assetIdx}`
        : `showcasing the visual reference from ${assetIdx}`
    );
  }
  if (customEnvironmentImageTag) {
    imageRefs.push(
      `composited realistically over the virtual studio background from ${customEnvironmentImageTag}`
    );
  }
  const refPrefix = imageRefs.length > 0 ? `${imageRefs.join(", ")}. ` : "";

  let actionDirection = "";
  let spokenLines = [];

  if (effectivePromoType === "product") {
    if (effectiveStyle === "unboxing") {
      actionDirection = `The influencer unboxes and holds up "${cleanName}" close to the camera with an impressed, excited expression, demonstrating its quality.`;
    } else if (effectiveStyle === "problem-solution") {
      actionDirection = `The influencer starts with a relatable frustrated look, then smiles brightly while holding up "${cleanName}" as the ultimate solution.`;
    } else {
      actionDirection = `The influencer holds "${cleanName}" naturally in hand, showing it to the camera and demonstrating how it works while speaking enthusiastically.`;
    }
    spokenLines = tpl.product(cleanName, cleanBenefit, cleanCta);
  } else if (effectivePromoType === "service") {
    if (effectiveStyle === "explainer") {
      actionDirection = `The influencer explains clearly with confident hand gestures how the service "${cleanName}" works and why it stands out.`;
    } else if (effectiveStyle === "urgency") {
      actionDirection = `The influencer leans in closer to the camera with high energy, sharing an exclusive opportunity with "${cleanName}".`;
    } else {
      actionDirection = `The influencer shares a genuine, trustworthy recommendation for the service "${cleanName}" with a warm smile.`;
    }
    spokenLines = tpl.service(cleanName, cleanBenefit, cleanCta);
  } else {
    if (effectiveStyle === "reaction") {
      actionDirection = `The influencer reacts with genuine surprise and excitement while pointing toward the screen/video topic "${cleanName}" and talking to the viewer.`;
    } else if (effectiveStyle === "summary") {
      actionDirection = `The influencer counts key takeaways on their fingers with dynamic energy, promoting the video "${cleanName}".`;
    } else {
      actionDirection = `The influencer hooks the viewer immediately with an intrigued expression, inviting them to watch the video "${cleanName}".`;
    }
    spokenLines = tpl.video(cleanName, cleanBenefit, cleanCta);
  }

  const extra = extraNotes.trim() ? ` ${extraNotes.trim()}.` : "";

  const singleScript = `${refPrefix}${actorDescription} ${actionDirection}${extra} Speaking in ${langObj.speechLanguage} with natural lip-sync: "${spokenLines.join(" ")}"`;

  const multiScenes = [
    {
      label: `Escena 1 (Hook • ${langObj.label})`,
      prompt: `${refPrefix}${actorDescription} Opening hook, looking directly into the lens with expressive energy. ${actionDirection} Speaking in ${langObj.speechLanguage}: "${spokenLines[0]}"`,
    },
    {
      label: `Escena 2 (Demostración • ${langObj.label})`,
      prompt: `${refPrefix}${actorDescription} Close-up and medium shot showcasing "${cleanName}" and highlighting its value.${extra} Speaking in ${langObj.speechLanguage}: "${spokenLines[1]}"`,
    },
    {
      label: `Escena 3 (CTA • ${langObj.label})`,
      prompt: `${refPrefix}${actorDescription} Smiling confidently at the camera, pointing down to the link with a clear call to action. Speaking in ${langObj.speechLanguage}: "${spokenLines[2]}"`,
    },
  ];

  return {
    singleScript,
    multiScenes,
  };
}
